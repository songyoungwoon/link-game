"""Reproducible two-address NPC journey worlds; original art, no external tools.

Each server simulates a durable traveler. Script below only presents observations.
Defaults are two processes on one computer; pass routable IPv4 hosts for two PCs.
"""
from __future__ import annotations
import argparse
import hashlib
import ipaddress
import json
import math
from pathlib import Path

PROJECT = Path(__file__).resolve().parents[1]
ARRIVAL = [0, 0, 3]
PORTAL_POSITION = [0, 1.5, -4]
PORTAL_SIZE = [2, 3, 1]
BOUNDS = {"min": [-8, 0, -8], "max": [8, 4, 8]}


def compact(value):
    return json.dumps(value, ensure_ascii=False, separators=(",", ":"), allow_nan=False)


class Scene:
    def __init__(self):
        self.roots = []
        self.ids = set()

    def node(self, kind, key, parent=None, **fields):
        if key in self.ids:
            raise ValueError("Duplicate node ID: " + key)
        self.ids.add(key)
        value = [kind, key, fields, []]
        (self.roots if parent is None else parent[3]).append(value)
        return value

    def component(self, key, parent, **fields):
        return self.node("component", key, parent, **fields)

    def element(self, key, parent, geometry, material, position=(0, 0, 0), **fields):
        return self.node("element", key, parent, geometry=geometry, style=material,
                         position=list(position), **fields)

    def box(self, key, parent, size, material, position=(0, 0, 0), **fields):
        return self.element(key, parent, {"type": "box", "size": list(size)}, material, position, **fields)

    def sphere(self, key, parent, radius, material, position=(0, 0, 0), **fields):
        return self.element(key, parent, {"type": "sphere", "radius": radius}, material, position, **fields)

    def cylinder(self, key, parent, radius, top, height, material, position=(0, 0, 0), **fields):
        return self.element(key, parent, {"type": "cylinder", "radius": radius,
                            "radiusTop": top, "height": height}, material, position, **fields)

    def text(self, key, parent, size, content, position, material="letter", **fields):
        return self.element(key, parent, {"type": "plane", "size": list(size)}, material,
                            position, text=content, raycast=False, **fields)

    def render(self):
        def emit(node, depth):
            kind, key, fields, children = node
            pad = "  " * depth
            lines = [f"{pad}{kind} {key} {{"]
            lines += [f"{pad}  {field}:{compact(value)};" for field, value in fields.items()]
            for child in children:
                lines.extend(emit(child, depth + 1))
            return lines + [pad + "}"]
        lines = ["// Original LINK journey court. Generated by tools/generate_npc_journey.py.", "scene {"]
        for root in self.roots:
            lines.extend(emit(root, 1))
        return "\n".join(lines + ["}", ""])


SCRIPT = r'''// Presentation only. Authority and portal travel live on the servers.
on onStart(ctx) {
 store npcId = "";
 store renderEpoch = 0;
 store currentX = 0;
 store currentY = 0;
 store currentZ = 3;
 store currentYaw = 180;
 store wasVisible = false;
 ctx.setTransform("npc_slot",{visible:false});
 ctx.playAnimation("traveler_model","Idle",true,1);
}
on onUpdate(ctx, deltaSeconds) {
 let snapshot = ctx.getSharedState();
 let selected = null;
 if (snapshot != null) {
  for (let npc of snapshot.npcs) {
   if (selected == null && npc.kind == "liora") { selected = npc; }
  }
 }
 if (selected == null) {
  ctx.setTransform("npc_slot",{visible:false});
  wasVisible = false;
  ctx.setText("traveler_status","WAITING FOR LIORA\nHer journey continues on the other server.");
 } else {
  let targetYaw = (selected.yaw + 360) % 360;
  if (!wasVisible || npcId != selected.id || renderEpoch != selected.epoch) {
   currentX = selected.position[0];
   currentY = selected.position[1];
   currentZ = selected.position[2];
   currentYaw = targetYaw;
  } else {
   let blend = min(1,deltaSeconds * 14);
   currentX = mix(currentX,selected.position[0],blend);
   currentY = mix(currentY,selected.position[1],blend);
   currentZ = mix(currentZ,selected.position[2],blend);
   currentYaw = (currentYaw + ((targetYaw - currentYaw + 540) % 360 - 180) * blend + 360) % 360;
  }
  npcId = selected.id;
  renderEpoch = selected.epoch;
  wasVisible = true;
  ctx.setTransform("npc_slot",{visible:true});
  ctx.setTransform("traveler_model",{position:[currentX,currentY,currentZ],rotation:[0,currentYaw,0],visible:true});
  if (selected.animation == "Walk") { ctx.playAnimation("traveler_model","Walk",true,1); }
  else { ctx.playAnimation("traveler_model","Idle",true,1); }
  ctx.setText("traveler_status",selected.name + "  /  " + selected.id + "\nJourneys " + str(selected.journey) + "    Epoch " + str(selected.epoch));
 }
}
'''


def build_scene(side):
    scene = Scene()
    obj = scene.node("object", "journey_court", name="The Wayfarer's Passage")
    court = scene.component("court", obj, raycast=False)
    scene.box("island", court, [21, 2, 21], "island", (0, -1.05, -.5))
    scene.box("lawn", court, [20.7, .12, 20.7], "lawn", (0, -.09, -.5))
    scene.box("court_floor", court, [10, .10, 11], "paving", (0, -.03, -.7))
    # The path is level. Decorative edging stays outside the NPC route.
    for i in range(7):
        scene.box(f"floor_joint_x_{i}", court, [.022, .006, 11], "joint", (-4.5 + i * 1.5, .025, -.7))
    for i in range(8):
        scene.box(f"floor_joint_z_{i}", court, [10, .006, .022], "joint", (0, .025, -5.5 + i * 1.5))
    for side_sign in (-1, 1):
        scene.box(f"side_inlay_{side_sign + 1}", court, [.055, .008, 11], "inlay", (side_sign * 4.72, .029, -.7))
    for i, (x, z) in enumerate([(0, 3), (-2, 1), (0, -3.45)]):
        scene.cylinder(f"route_inlay_{i}", court, .29, .29, .008, "inlay", (x, .035, z))
    # A carved open gateway frames the same AABB used by the server.
    gate = scene.component("gateway", obj, raycast=False)
    for sign in (-1, 1):
        key = "left" if sign < 0 else "right"
        x = sign * 1.28
        scene.box("gate_foot_" + key, gate, [.68, .18, .94], "stone", (x, .09, -4))
        scene.box("gate_column_" + key, gate, [.36, 2.85, .48], "stone", (x, 1.57, -4))
        scene.box("gate_line_" + key, gate, [.055, 2.55, .025], "glow", (x, 1.57, -3.748))
        scene.box("gate_capital_" + key, gate, [.66, .20, .76], "trim", (x, 3.10, -4))
    for i in range(15):
        angle = math.pi * i / 14
        x, y = math.cos(angle) * 1.28, 3.17 + math.sin(angle) * 1.28
        scene.box(f"arch_segment_{i}", gate, [.27, .36, .61], "trim", (x, y, -4),
                  rotation=[0, 0, math.degrees(angle) - 90])
    for i in range(25):
        angle = math.pi * i / 24
        x, y = math.cos(angle) * 1.10, 3.17 + math.sin(angle) * 1.10
        scene.sphere(f"arch_rune_{i}", gate, .037, "glow", (x, y, -3.66))
    scene.element("portal_veil", gate, {"type": "plane", "size": [2.07, 3.12]}, "veil", (0, 1.63, -4.03))
    scene.box("portal_threshold", gate, [2.05, .025, 1], "inlay", (0, .028, -4))
    scene.text("destination_name", gate, [2.5, .30], "TO DAWN COURT" if side else "TO AZURE COURT", (0, 3.08, -3.64), "title")
    # Layered terraces/planters mark the edge; no hidden geometry physics implied.
    for i, (x, z) in enumerate([(-6.1, 3.2), (6.1, 2), (-6.1, -2.8), (6.1, -4.6)]):
        scene.box(f"planter_base_{i}", court, [1.9, .28, 2.3], "stone", (x, .14, z))
        scene.box(f"planter_soil_{i}", court, [1.65, .06, 2.05], "soil", (x, .30, z))
        for k in range(3):
            px, pz = x + (k - 1) * .43, z + .13 * (k % 2)
            scene.cylinder(f"stem_{i}_{k}", court, .045, .025, .72, "stem", (px, .69, pz))
            scene.sphere(f"foliage_{i}_{k}", court, .43, "leaf", (px, 1.15, pz), scale=[1, .7, .85])
            scene.sphere(f"petal_{i}_{k}", court, .15, "petal", (px + .11, 1.44, pz - .04))
    for i, (x, z) in enumerate([(-4.1, 3.5), (4.1, -2), (-4.1, -4.9), (4.1, 3.5)]):
        scene.cylinder(f"lantern_pedestal_{i}", court, .20, .15, .72, "stone", (x, .36, z))
        scene.sphere(f"lantern_{i}", court, .13, "glow", (x, .87, z))
        scene.cylinder(f"lantern_top_{i}", court, .23, .03, .18, "trim", (x, 1.03, z))
    for sign in (-1, 1):
        for k in range(3):
            scene.box(f"rear_wall_{sign+1}_{k}", court, [1.6, 1.05 + k * .17, .44], "stone",
                      (sign * (2.75 + k * 1.55), .52 + k * .085, -6.4))
    for i in range(9):
        x = -15 + i * 4
        h = 6 + 2.0 * math.sin(i * 1.4 + side)
        scene.sphere(f"ridge_{i}", court, 1, "ridge", (x, 1.2, -20 - i % 3), scale=[5.5, h, 3.5])
    scene.sphere("sun", court, 1.55, "sun", (-11 if side == 0 else 12, 12, -26))
    inscriptions = scene.component("inscriptions", obj, raycast=False)
    scene.text("world_title", inscriptions, [5.4, .48], "AZURE COURT" if side else "DAWN COURT", (0, 5.38, -4.3), "title")
    scene.text("world_subtitle", inscriptions, [5.6, .24], "EVERY WORLD. ONE JOURNEY.", (0, 4.91, -4.25), "letter")
    scene.box("observation_plinth", inscriptions, [3.75, .78, .34], "sign", (3.05, .57, 3.1), rotation=[0, 24, 0])
    scene.text("traveler_status", inscriptions, [3.45, .65], "CONNECTING TO THE JOURNEY\nNPCs travel while no one is watching.", (3.12, 1.10, 3.27), "letter", rotation=[0, 24, 0])
    scene.text("journey_hint", inscriptions, [3.75, .55], "Watch Liora enter the portal.\nFollow her to the other server.", (-3.05, 1.12, 3.2), "letter", rotation=[0, -18, 0])
    scene.box("hint_plinth", inscriptions, [3.96, .78, .34], "sign", (-3.11, .57, 3.03), rotation=[0, -18, 0])
    npc = scene.component("npc_slot", obj, name="Server-owned Liora", visible=False, script="scripts/traveler.script")
    scene.element("traveler_model", npc, {"type": "model", "source": "models/liora.glb"}, "hero", ARRIVAL, raycast=False)
    return scene


def style(side):
    colors = ({"island":"#71635B", "lawn":"#8B9C7A", "paving":"#C4B49C", "joint":"#A99A82", "inlay":"#D4B882",
               "stone":"#DDD2B8", "trim":"#E8D9B3", "glow":"#FCDB9A", "veil":"#E8BF82", "soil":"#6C6F56", "stem":"#68765A",
               "leaf":"#8B9B72", "petal":"#EAD9B7", "ridge":"#A7AC97", "sun":"#FFE8BF", "sign":"#384B43", "letter":"#F5EBD6"},
              {"island":"#425163", "lawn":"#657F85", "paving":"#9CAEB8", "joint":"#7C919B", "inlay":"#86CBDB",
               "stone":"#BBCBCE", "trim":"#D4E2E1", "glow":"#A6EEFF", "veil":"#72C7E6", "soil":"#505F70", "stem":"#627C77",
               "leaf":"#809F9D", "petal":"#D4BEEB", "ridge":"#8C9EAF", "sun":"#D5F1FF", "sign":"#273E56", "letter":"#E8F2FA"})[side]
    lines = ['defaults {color:"#FFFFFF";opacity:1;emission:0;roughness:.86;metalness:0;}']
    for name, color in colors.items():
        props = {"color": color}
        if name == "veil":
            props.update(opacity=.20, emission=.30)
        if name in ("glow", "sun"):
            props["emission"] = 1.2
        if name == "letter":
            props.update(textBackground=False, emission=.10)
        lines.append("material " + name + " {" + "".join(k + ":" + compact(v) + ";" for k, v in props.items()) + "}")
    # Do not override imported glTF roughness or metalness for the character.
    lines += ['material hero {color:"#FFFFFF";shading:"toon";outline:.0048;}',
              'material title {color:"' + colors['letter'] + '";textBackground:false;emission:.10;}']
    # Defaults roughness/metalness affect imported factors; omit those defaults.
    lines[0] = 'defaults {color:"#FFFFFF";opacity:1;emission:0;}'
    return "\n".join(lines) + "\n"


def generate(args):
    for host in (args.host_a, args.host_b):
        ipaddress.IPv4Address(host)
        if host == "0.0.0.0":
            raise ValueError("Use a reachable client IPv4 address, not a wildcard bind address.")
    if any(not 1 <= port <= 65535 for port in (args.port_a, args.port_b)):
        raise ValueError("Port must be between 1 and 65535.")
    if (args.host_a, args.port_a) == (args.host_b, args.port_b):
        raise ValueError("The two servers require distinct host/port pairs.")
    addresses = [f"link://{args.host_a}:{args.port_a}/traveler-a", f"link://{args.host_b}:{args.port_b}/traveler-b"]
    hero = (PROJECT / 'worlds/moon-garden/models/hero.glb').read_bytes()
    source_sha = hashlib.sha256(hero).hexdigest()
    reports = []
    configroot = PROJECT / 'configs'
    configroot.mkdir(exist_ok=True)
    for side in (0, 1):
        key, peer = ('traveler-a', 'traveler-b')[side], addresses[1 - side]
        root = PROJECT / 'worlds' / key
        (root / 'models').mkdir(parents=True, exist_ok=True)
        (root / 'scripts').mkdir(exist_ok=True)
        scene = build_scene(side)
        if len(scene.ids) > 500:
            raise ValueError('Scene exceeds the Browser node budget.')
        world = {"version": "0.1", "id": key, "name": "The Wayfarer's Passage / " + ('Dawn Court', 'Azure Court')[side],
                 "elements": "scene.element", "style": "appearance.style", "scripts": ["scripts/traveler.script"],
                 "extensions": ["models-v1", "npc-travel-v1"],
                 "entry": {"position": [5.2, 1.65, 4.6], "target": [0, 1, -1]},
                 "environment": {"background": ('#D7D5C6', '#B6CBDD')[side], "grid": False,
                                 "fog": {"color": ('#D7D5C6', '#B6CBDD')[side], "start": 18, "end": 48}},
                 "walk": {**BOUNDS, "eyeHeight": 1.65, "speed": 2},
                 "portals": [{"id": "wayfarer_gate", "address": peer, "position": PORTAL_POSITION, "size": PORTAL_SIZE}]}
        files = {'world.link': 'world {\n' + ''.join(' ' + k + ':' + compact(v) + ';\n' for k, v in world.items()) + '}\n',
                 'scene.element': scene.render(), 'appearance.style': style(side), 'scripts/traveler.script': SCRIPT}
        for name, data in files.items():
            (root / name).write_text(data, encoding='utf-8', newline='\n')
        (root / 'models/liora.glb').write_bytes(hero)
        config = {"version": 1, "authority": addresses[side], "peers": [peer], "bounds": BOUNDS, "arrival": ARRIVAL,
                  "route": [{"position": [-2, 0, 1], "wait": 2},
                            {"position": [0, 0, -4], "portal": {"address": peer, "arrival": ARRIVAL,
                              "position": PORTAL_POSITION, "size": PORTAL_SIZE}}],
                  "seeds": [{"id": "wayfarer-01", "kind": "liora", "name": "Liora", "position": ARRIVAL, "yaw": 180}] if side == 0 else [],
                  "speed": .8}
        (configroot / ('npc-' + key + '.json')).write_text(json.dumps(config, indent=2) + '\n', encoding='utf-8', newline='\n')
        report = {"world": key, "address": addresses[side], "peer": peer, "generator": "tools/generate_npc_journey.py",
                  "license": "Apache-2.0", "nodes": len(scene.ids), "model": {"source": "../moon-garden/models/hero.glb", "file": "models/liora.glb",
                  "sha256": source_sha, "bytes": len(hero), "character": "Liora - original Garden Wayfarer", "joints": 21, "clips": ["Idle", "Walk", "Attack"]}}
        (root / 'asset-report.json').write_text(json.dumps(report, indent=2) + '\n', encoding='utf-8', newline='\n')
        reports.append(report)
    print(json.dumps({"worlds": reports}, indent=2))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--host-a', default='127.0.0.1')
    parser.add_argument('--host-b', default='127.0.0.1')
    parser.add_argument('--port-a', default=8010, type=int)
    parser.add_argument('--port-b', default=8011, type=int)
    generate(parser.parse_args())


if __name__ == '__main__':
    main()
